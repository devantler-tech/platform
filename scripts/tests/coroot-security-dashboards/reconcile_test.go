const ownership = "> 🤖 Generated by the Agentic Engineer\n\nManaged by platform GitOps: coroot-security-progress/v1.\n"

type dashboard struct {
	ID          string          `json:"id"`
	Name        string          `json:"name"`
	Description string          `json:"description"`
	Config      json.RawMessage `json:"config"`
}

type request struct {
	Action string `json:"action"`
	dashboard
}

// The API fixture follows v1.22.2 api/api.go, api/views/users/users.go and
// db/dashboards.go: list/detail wrap data, create returns a plain ID, and the
// detail GET omits the stored description. It rejects malformed write forms.
type coroot struct {
	mu             sync.Mutex
	dashboards     []dashboard
	projects       []map[string]string
	posts          []request
	override       func(http.ResponseWriter, *http.Request) bool
	writeFailure   string
	discardSave    bool
	unexpectedPath string
}

func newCoroot() *coroot {
	return &coroot{projects: []map[string]string{{"id": "project/a?#", "name": "platform"}}}
}

func (c *coroot) serve(w http.ResponseWriter, r *http.Request) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.override != nil && c.override(w, r) {
		return
	}
	if r.Method == http.MethodGet && r.URL.Path == "/api/user" {
		_ = json.NewEncoder(w).Encode(map[string]any{"name": "Anonymous", "role": "Admin", "anonymous": true, "projects": c.projects})
		return
	}
	prefix := "/api/project/project%2Fa%3F%23/dashboards"
	path := r.URL.EscapedPath()
	if !strings.HasPrefix(path, prefix) || (path != prefix && !strings.HasPrefix(path, prefix+"/")) {
		c.unexpectedPath = path
		http.Error(w, "unexpected path", http.StatusNotFound)
		return
	}
	id := strings.TrimPrefix(r.URL.Path, "/api/project/project/a?#/dashboards")
	id = strings.TrimPrefix(id, "/")
	if r.Method == http.MethodGet {
		var data any
		if id == "" {
			rows := make([]map[string]any, 0, len(c.dashboards))
			for _, d := range c.dashboards {
				rows = append(rows, map[string]any{"id": d.ID, "name": d.Name, "description": d.Description})
			}
			data = rows
		} else {
			for _, d := range c.dashboards {
				if d.ID == id {
					d.Description = ""
					data = d
				}
			}
			if data == nil {
				http.NotFound(w, r)
				return
			}
		}
		_ = json.NewEncoder(w).Encode(map[string]any{"context": map[string]string{"project_id": "project/a?#"}, "data": data})
		return
	}
	if r.Method != http.MethodPost {
		http.Error(w, "only GET and POST", http.StatusMethodNotAllowed)
		return
	}
	var req request
	decoder := json.NewDecoder(r.Body)
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&req); err != nil || req.Name == "" {
		http.Error(w, "invalid flat DashboardForm", http.StatusBadRequest)
		return
	}
	c.posts = append(c.posts, req)
	action := req.Action
	if action == "" {
		action = "save"
	}
	if action == c.writeFailure {
		http.Error(w, "PRIVATE response must not appear in logs", http.StatusInternalServerError)
		return
	}
	if action == "create" && id == "" {
		req.ID = fmt.Sprintf("new/id ?#%d", len(c.dashboards))
		req.Config = json.RawMessage(`{"groups":null}`)
		c.dashboards = append(c.dashboards, req.dashboard)
		w.WriteHeader(http.StatusCreated)
		_, _ = fmt.Fprintln(w, req.ID)
		return
	}
	for i, d := range c.dashboards {
		if d.ID != id {
			continue
		}
		switch action {
		case "update":
			c.dashboards[i].Name = req.Name
			c.dashboards[i].Description = req.Description
		case "save":
			if len(req.Config) == 0 {
				http.Error(w, "save has no config", http.StatusBadRequest)
				return
			}
			if !c.discardSave {
				c.dashboards[i].Config = req.Config
			}
		default:
			http.Error(w, "unsafe action", http.StatusBadRequest)
			return
		}
		return
	}
	http.NotFound(w, r)
}

func desired() dashboard {
	return dashboard{Name: "Platform security progress", Description: ownership + "Track remaining work.", Config: json.RawMessage(`{"groups":[{"name":"Overview","panels":[],"collapsed":false}]}`)}
}

func run(t *testing.T, server *httptest.Server, definitions []dashboard, extra ...string) (string, error) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "dashboards.json")
	encoded, err := json.Marshal(definitions)
	if err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile(path, encoded, 0o600); err != nil {
		t.Fatal(err)
	}
	return runFile(t, server, path, extra...)
}

func runFile(t *testing.T, server *httptest.Server, path string, extra ...string) (string, error) {
	t.Helper()
	ctx, cancel := context.WithTimeout(t.Context(), 15*time.Second)
	defer cancel()
	script := filepath.Join("..", "..", "..", "k8s", "bases", "infrastructure", "coroot", "components", "security-progress", "reconcile.sh")
	cmd := exec.CommandContext(ctx, "sh", script)
	cmd.Env = append(os.Environ(), "COROOT_URL="+server.URL, "COROOT_PROJECT=platform", "DASHBOARDS_FILE="+path,
		"COROOT_CONNECT_TIMEOUT=1", "COROOT_REQUEST_TIMEOUT=2")
	cmd.Env = append(cmd.Env, extra...)
	output, err := cmd.CombinedOutput()
	return string(output), err
}

func assertConfig(t *testing.T, got, want json.RawMessage) {
	t.Helper()
	var a, b any
	if json.Unmarshal(got, &a) != nil || json.Unmarshal(want, &b) != nil || !reflect.DeepEqual(a, b) {
		t.Fatalf("config mismatch: got %s, want %s", got, want)
	}
}

// A create retry after a lost response, an incorrect API form, or a steady-state
// write would fail this lifecycle test. Unrelated dashboards must survive.
func TestCreateThenNoopPreservesUnrelated(t *testing.T) {
	c := newCoroot()
	unrelated := dashboard{ID: "personal", Name: "My dashboard", Description: "Unmanaged", Config: json.RawMessage(`{"groups":[]}`)}
	c.dashboards = []dashboard{unrelated}
	s := httptest.NewServer(http.HandlerFunc(c.serve))
	defer s.Close()
	d := desired()
	for pass := range 2 {
		output, err := run(t, s, []dashboard{d})
		if err != nil {
			t.Fatalf("pass %d failed: %v\n%s", pass, err, output)
		}
		if len(c.posts) != 2 || c.posts[0].Action != "create" || c.posts[1].Action != "" {
			t.Fatalf("expected one create and one save across both runs; got %+v", c.posts)
		}
		if !reflect.DeepEqual(c.dashboards[0], unrelated) {
			t.Fatal("unrelated dashboard changed")
		}
		assertConfig(t, c.dashboards[1].Config, d.Config)
	}
	if c.unexpectedPath != "" {
		t.Fatalf("IDs were not safely encoded: %s", c.unexpectedPath)
	}
}

func TestRepairsOwnedConfigAndDescription(t *testing.T) {
	c := newCoroot()
	d := desired()
	old := d
	old.ID = "existing"
	old.Description = ownership + "Previous version."
	old.Config = json.RawMessage(`{"groups":[]}`)
	c.dashboards = []dashboard{old}
	s := httptest.NewServer(http.HandlerFunc(c.serve))
	defer s.Close()
	for range 2 {
		output, err := run(t, s, []dashboard{d})
		if err != nil {
			t.Fatalf("reconcile failed: %v\n%s", err, output)
		}
	}
	if len(c.posts) != 2 || c.dashboards[0].Description != d.Description {
		t.Fatalf("expected only one metadata repair and one config save: %+v", c.posts)
	}
	assertConfig(t, c.dashboards[0].Config, d.Config)
}

func TestOwnershipCollisionPreventsEveryWrite(t *testing.T) {
	for _, duplicate := range []bool{false, true} {
		t.Run(fmt.Sprint("duplicate=", duplicate), func(t *testing.T) {
			c := newCoroot()
			second := desired()
			second.Name = "Kubescape remediation progress"
			occupied := second
			occupied.ID = "occupied"
			if !duplicate {
				occupied.Description = "An operator created this."
			}
			c.dashboards = []dashboard{occupied}
			if duplicate {
				other := occupied
				other.ID = "duplicate"
				c.dashboards = append(c.dashboards, other)
			}
			s := httptest.NewServer(http.HandlerFunc(c.serve))
			defer s.Close()
			output, err := run(t, s, []dashboard{desired(), second})
			if err == nil || len(c.posts) != 0 {
				t.Fatalf("collision was not refused before writes: %v; posts=%+v; %s", err, c.posts, output)
			}
		})
	}
}

func TestInvalidReadsNeverTriggerWrites(t *testing.T) {
	for _, tc := range []struct{ path, body string }{
		{"/api/user", `{"projects":[]}`},
		{"/api/user", `{"projects":[{"id":"one","name":"platform"},{"id":"two","name":"platform"}]}`},
		{"/dashboards", `{"context":{},"data":null}`},
		{"/dashboards", `{"context":{},"data":"not an array"}`},
		{"/dashboards", `not JSON`},
		{"/dashboards/existing", `{"context":{},"data":null}`},
		{"/dashboards/existing", `{"data":{"id":"wrong","name":"Platform security progress","config":{"groups":[]}}}`},
	} {
		t.Run(tc.path+tc.body, func(t *testing.T) {
			c := newCoroot()
			d := desired()
			d.ID = "existing"
			c.dashboards = []dashboard{d}
			c.override = func(w http.ResponseWriter, r *http.Request) bool {
				if r.Method == http.MethodGet && strings.HasSuffix(r.URL.Path, tc.path) {
					_, _ = w.Write([]byte(tc.body))
					return true
				}
				return false
			}
			s := httptest.NewServer(http.HandlerFunc(c.serve))
			defer s.Close()
			output, err := run(t, s, []dashboard{desired()})
			if err == nil || len(c.posts) != 0 {
				t.Fatalf("invalid read did not fail closed: %v; posts=%+v; %s", err, c.posts, output)
			}
		})
	}
}

func TestFailedWritesStopWithoutRetryOrResponseLeak(t *testing.T) {
	for _, action := range []string{"create", "save", "update"} {
		t.Run(action, func(t *testing.T) {
			c := newCoroot()
			c.writeFailure = action
			if action != "create" {
				old := desired()
				old.ID = "existing"
				old.Config = json.RawMessage(`{"groups":[]}`)
				if action == "update" {
					old.Description = ownership + "Old metadata"
				}
				c.dashboards = []dashboard{old}
			}
			s := httptest.NewServer(http.HandlerFunc(c.serve))
			defer s.Close()
			output, err := run(t, s, []dashboard{desired()})
			if err == nil || len(c.posts) != 1 || strings.Contains(output, "PRIVATE") {
				t.Fatalf("failed write retried, leaked, or succeeded: %v; posts=%+v; %s", err, c.posts, output)
			}
		})
	}
}

