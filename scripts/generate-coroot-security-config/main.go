// Command generate-coroot-security-config packages reviewed scripts for Flux.
// Run from the repository root. Never edit the generated ConfigMap by hand.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"unicode/utf16"

	"gopkg.in/yaml.v3"
)

func main() {
	check := flag.Bool("check", false, "check generated content without changing it")
	flag.Parse()
	dir := "k8s/bases/infrastructure/coroot/components/security-progress"
	files := map[string]string{
		"bind-project-metrics.sh":            filepath.Join(dir, "bind-project-metrics.sh"),
		"collector.sh":                       filepath.Join(dir, "collector.sh"),
		"reconcile.sh":                       filepath.Join(dir, "reconcile.sh"),
		"metrics.jq":                         filepath.Join(dir, "metrics.jq"),
		"dashboards.json":                    filepath.Join(dir, "dashboards.json"),
		"prometheus.yml":                     filepath.Join(dir, "prometheus.conf"),
		"check-kubescape-result-coverage.sh": "scripts/check-kubescape-result-coverage.sh",
		"kubescape-unscanned-namespaces.tsv": "scripts/kubescape-unscanned-namespaces.tsv",
	}
	data := map[string]*yaml.Node{}
	for name, path := range files {
		b, err := os.ReadFile(path)
		if err != nil {
			fail(err)
		}
		if strings.HasSuffix(name, ".json") {
			if !json.Valid(b) {
				fail(fmt.Errorf("invalid source JSON: %s", path))
			}
			// YAML emitters quote/fold strings containing non-BMP glyphs even
			// when literal style is requested. JSON Unicode escapes preserve the
			// decoded dashboard and keep the embedded-JSON gate's literal block.
			var ascii strings.Builder
			for _, r := range string(b) {
				if r <= 127 {
					ascii.WriteRune(r)
					continue
				}
				for _, unit := range utf16.Encode([]rune{r}) {
					fmt.Fprintf(&ascii, "\\u%04x", unit)
				}
			}
			b = []byte(ascii.String())
		}
		// Flux substitutes the entire rendered YAML. Escape shell substitutions
		// in the generated copy only; the ordinary source remains executable.
		data[name] = &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Style: yaml.LiteralStyle,
			Value: strings.ReplaceAll(string(b), "${", "$${")}
	}
	cm := map[string]any{"apiVersion": "v1", "kind": "ConfigMap", "metadata": map[string]any{"name": "coroot-security-progress", "namespace": "observability"}, "data": data}
	b, err := yaml.Marshal(cm)
	if err != nil {
		fail(err)
	}
	b = append([]byte("# Generated by go run ./scripts/generate-coroot-security-config; DO NOT EDIT.\n"), b...)
	output := filepath.Join(dir, "config-map.yaml")
	if *check {
		current, err := os.ReadFile(output)
		if err != nil {
			fail(err)
		}
		if !bytes.Equal(b, current) {
			fail(fmt.Errorf("security-progress ConfigMap is stale; run go run ./scripts/generate-coroot-security-config"))
		}
		return
	}
	if err := os.WriteFile(output, b, 0644); err != nil {
		fail(err)
	}
}

func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
