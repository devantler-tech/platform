#!/usr/bin/env bash
# Project only the complete credential-free offline job; never export the publisher.
set -euo pipefail
[[ $# -le 2 ]] || {
  echo 'Usage: generate-release-recovery-fixture.sh [source [destination]]' >&2
  exit 2
}
root="$(cd "$(dirname "$0")/.." && pwd)"
source="${1:-$root/.github/workflows/publish-release-recovery.yaml}"
destination="${2:-$root/.github/workflows/release-recovery-offline-fixture.yaml}"
work="$(mktemp)"
trap 'rm -f "$work"' EXIT
yq '
  .name = "Internal release-recovery offline fixture" |
  .on = {"workflow_call": {"inputs": (.on.workflow_dispatch.inputs |
    with_entries(select(.key == "enable-recovery" or .key == "offline-test")))}} |
  .jobs = {"offline-test": .jobs.offline-test}
' "$source" >"$work"
{
  printf '# Generated by scripts/generate-release-recovery-fixture.sh; do not edit.\n'
  printf '# Internal credential-free native validation only, not a supported consumer interface.\n'
  cat "$work"
} >"$destination"
