#!/usr/bin/env bash
# Project only the credential-free offline steps; never export the publisher.
set -euo pipefail
[[ $# -le 2 ]] || {
  echo 'Usage: generate-release-recovery-fixture.sh [source [destination]]' >&2
  exit 2
}
root="$(cd "$(dirname "$0")/.." && pwd)"
source="${1:-$root/.github/workflows/publish-release-recovery.yaml}"
destination="${2:-$root/.github/actions/release-recovery-offline-fixture/action.yaml}"
work="$(mktemp)"
trap 'rm -f "$work"' EXIT
yq '
  {"name": "Internal release-recovery offline fixture",
   "description": "Credential-free recovery validation generated from the production offline job",
   "inputs": (.on.workflow_dispatch.inputs |
     with_entries(select(.key == "enable-recovery" or .key == "offline-test")) |
     with_entries(.value = {"description": .value.description, "required": false, "default": "false"})),
   "runs": {"using": "composite", "steps": (.jobs.offline-test.steps |
     map(.if = "inputs.enable-recovery == '\''true'\'' && inputs.offline-test == '\''true'\''" |
       if has("run") then .shell = "bash" else . end))}}
' "$source" >"$work"
mkdir -p "$(dirname "$destination")"
{
  printf '# Generated by scripts/generate-release-recovery-fixture.sh; do not edit.\n'
  printf '# Internal credential-free native validation only, not a supported consumer interface.\n'
  cat "$work"
} >"$destination"
