// Only fixed, reviewed public vocabulary crosses the publisher boundary.
// Source labels, resource identities, diagnostics and URLs are never inputs.
var routes = map[string]string{
	"cnpg-degraded": "Database health requires investigation",
}

var (
	errInput       = errors.New("invalid alert observation")
	errStore       = errors.New("alert state is unavailable or invalid")
	errFull        = errors.New("alert outbox capacity requires attention")
	errAmbiguous   = errors.New("alert write is unconfirmed; reconcile before retrying")
	errQuarantined = errors.New("alert publication requires operator reconciliation")
)

type retryError struct{ after time.Time }

func (e *retryError) Error() string {
	return "alert publication deferred by authentication or rate limit"
}

type observation struct {
	Route      string    `json:"route"`
	State      string    `json:"state"`
	ObservedAt time.Time `json:"observedAt"`
	Complete   bool      `json:"complete"`
}

func decodeObservation(r io.Reader) (observation, error) {
	var v observation
	b, err := io.ReadAll(io.LimitReader(r, 4097))
	if err != nil || len(b) > 4096 {
		return v, errInput
	}
	d := json.NewDecoder(strings.NewReader(string(b)))
	d.DisallowUnknownFields()
	if d.Decode(&v) != nil || !errors.Is(d.Decode(new(any)), io.EOF) {
		return observation{}, errInput
	}
	if _, ok := routes[v.Route]; !ok {
		return observation{}, errInput
	}
	if v.State != "firing" && v.State != "healthy" && v.State != "unknown" {
		return observation{}, errInput
	}
	if v.ObservedAt.IsZero() || v.State == "healthy" && !v.Complete {
		return observation{}, errInput
	}
	return v, nil
}

type routeState struct {
	ObservedAt time.Time `json:"observedAt"`
	State      string    `json:"state"`
	Episode    string    `json:"episode"`
	Issue      int       `json:"issue"`
}
type operation struct {
	ID        string    `json:"id"`
	Episode   string    `json:"episode"`
	Route     string    `json:"route"`
	State     string    `json:"state"`
	CreatedAt time.Time `json:"createdAt"`
	Issue     int       `json:"issue"`
	Sent      bool      `json:"sent"`
	Attempts  int       `json:"attempts"`
	RetryAt   time.Time `json:"retryAt"`
}
type receipt struct {
	Issue   int
	Comment int
}
type deliveryReceipt struct {
	Operation  string    `json:"operation"`
	Issue      int       `json:"issue"`
	Comment    int       `json:"comment"`
	VerifiedAt time.Time `json:"verifiedAt"`
}
type remoteIssue struct {
	Number int
	Body   string
}
type remoteComment struct {
	Issue int
	ID    int
	Body  string
}
type journal struct {
	Version      int                   `json:"version"`
	Routes       map[string]routeState `json:"routes"`
	Pending      []operation           `json:"pending"`
	Receipts     []deliveryReceipt     `json:"receipts"`
	AttemptDay   string                `json:"attemptDay"`
	AttemptCount int                   `json:"attemptCount"`
}
type githubAPI interface {
	verify(context.Context) error
	find(context.Context, operation) (receipt, error)
	isOpen(context.Context, int) (bool, error)
	write(context.Context, operation) error
}
type publisher struct {
	dir string
	api githubAPI
	now func() time.Time
}

func opaqueID() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", errStore
	}
	return hex.EncodeToString(b), nil
}
func (o operation) marker() string { return "<!-- alert-publisher:v1 operation=" + o.ID + " -->" }
func (o operation) body() string {
	message := "The detector reports an actionable condition. Investigate and track remediation in this issue."
	if o.State == "healthy" {
		message = "A complete detector observation reports recovery. This observation does not close outstanding remediation."
	}
	if o.State == "unknown" {
		message = "The signal is unconfirmed. Investigate the detector and retain any outstanding remediation."
	}
	mention := ""
	if o.Issue == 0 {
		mention = "\n\n@devantler"
	}
	return "> 🤖 Generated by the Agentic Engineer\n\n" + routes[o.Route] + ".\n\n" + message + mention + "\n\n" + o.marker()
}

func (p *publisher) run(ctx context.Context, e *observation) error {
	now := p.now().UTC()
	if e != nil {
		// Validate programmatic callers just as strictly as JSON callers.
		b, err := json.Marshal(e)
		if err != nil {
			return errInput
		}
		if _, err = decodeObservation(strings.NewReader(string(b))); err != nil {
			return err
		}
		if e.ObservedAt.After(now.Add(5*time.Minute)) || e.ObservedAt.Before(now.Add(-7*24*time.Hour)) {
			return errInput
		}
	}
	unlock, err := lockStore(ctx, p.dir)
	if err != nil {
		return err
	}
	defer unlock()
	s, err := readJournal(p.dir)
	if err != nil {
		return err
	}
	if e != nil {
		old := s.Routes[e.Route]
		if e.ObservedAt.Equal(old.ObservedAt) && e.State != old.State {
			return errInput
		}
		if e.ObservedAt.After(old.ObservedAt) {
			changed := old.State != e.State
			old.State = e.State
			old.ObservedAt = e.ObservedAt
			if changed && (e.State == "firing" || old.Episode != "") {
				if len(s.Pending) >= 64 {
					return errFull
				}
				if old.Episode == "" {
					old.Episode, err = opaqueID()
					if err != nil {
						return err
					}
				}
				id, idErr := opaqueID()
				if idErr != nil {
					return idErr
				}
				s.Pending = append(s.Pending, operation{ID: id, Episode: old.Episode, Route: e.Route, State: e.State, CreatedAt: now})
			}
			s.Routes[e.Route] = old
			if err = saveJournal(p.dir, s); err != nil {
				return err
			}
		}
	}
	if len(s.Pending) == 0 {
		return nil
	}
	if now.Sub(s.Pending[0].CreatedAt) > 7*24*time.Hour {
		return errQuarantined
	}
	for len(s.Pending) > 0 {
		now = p.now().UTC()
		op := s.Pending[0]
		if now.Sub(op.CreatedAt) > 7*24*time.Hour {
			return errQuarantined
		}
		if now.Before(op.RetryAt) {
			return &retryError{after: op.RetryAt}
		}
		if op.Sent {
			if err = p.api.verify(ctx); err != nil {
				return p.deferRead(err, &s, op)
			}
			r, findErr := p.api.find(ctx, op)
			if findErr != nil {
				return p.deferRead(findErr, &s, op)
			}
			if r.Issue == 0 {
				return errAmbiguous
			}
			now = p.now().UTC()
			retained := s.Receipts[:0]
			for _, old := range s.Receipts {
				if !old.VerifiedAt.Before(now.Add(-8 * 24 * time.Hour)) {
					retained = append(retained, old)
				}
			}
			s.Receipts = retained
			if len(s.Receipts) >= 128 {
				return errFull
			}
			s.Receipts = append(s.Receipts, deliveryReceipt{Operation: op.ID, Issue: r.Issue, Comment: r.Comment, VerifiedAt: now})
			state := s.Routes[op.Route]
			state.Issue = r.Issue
			s.Routes[op.Route] = state
			s.Pending = s.Pending[1:]
			if err = saveJournal(p.dir, s); err != nil {
				return err
			}
			continue
		}
		if op.Attempts >= 6 {
			return errQuarantined
		}
		// Issue binding comes only from a prior verified receipt in this journal.
		op.Issue = s.Routes[op.Route].Issue
		if op.Issue > 0 && op.State == "firing" {
			open, openErr := p.api.isOpen(ctx, op.Issue)
			if openErr != nil {
				return p.deferRead(openErr, &s, op)
			}
			if !open {
				op.Issue = 0
			}
		}
		if op.Issue == 0 && op.State != "firing" {
			return errQuarantined
		}
		if err = p.api.verify(ctx); err != nil {
			return p.deferRead(err, &s, op)
		}
		now = p.now().UTC()
		day := now.Format("2006-01-02")
		if s.AttemptDay != day {
			s.AttemptDay = day
			s.AttemptCount = 0
		}
		if s.AttemptCount >= 12 {
			return &retryError{after: now.Truncate(24 * time.Hour).Add(24 * time.Hour)}
		}
		op.Sent = true
		op.Attempts++
		s.Pending[0] = op
		s.AttemptCount++
		// A crash at any point after this commit is an ambiguous write, never
		// permission to repeat a POST. The next run reconciles its exact marker.
		if err = saveJournal(p.dir, s); err != nil {
			return err
		}
		err = p.api.write(ctx, op)
		if err != nil {
			var retry *retryError
			if errors.As(err, &retry) {
				op.Sent = false
				op.RetryAt = retry.after
				s.Pending[0] = op
				if saveJournal(p.dir, s) != nil {
					return errStore
				}
			}
			return err
		}
		// Even an HTTP201 is not a receipt until the bot-authored object is read.
	}
	return nil
}

func (p *publisher) deferRead(err error, s *journal, op operation) error {
	if errors.Is(err, errQuarantined) {
		return err
	}
	var retry *retryError
	if !errors.As(err, &retry) {
		retry = &retryError{after: p.now().UTC().Add(5 * time.Minute)}
	}
	op.RetryAt = retry.after
	s.Pending[0] = op
	if saveJournal(p.dir, *s) != nil {
		return errStore
	}
	return retry
}

func lockStore(ctx context.Context, dir string) (func(), error) {
	if os.MkdirAll(dir, 0700) != nil {
		return nil, errStore
	}
	info, err := os.Lstat(dir)
	if err != nil || !info.IsDir() || info.Mode().Perm()&0077 != 0 {
		return nil, errStore
	}
	f, err := os.OpenFile(filepath.Join(dir, "lock"), os.O_CREATE|os.O_RDWR|syscall.O_NOFOLLOW, 0600)
	if err != nil {
		return nil, errStore
	}
	lockInfo, err := f.Stat()
	if err != nil || !lockInfo.Mode().IsRegular() || lockInfo.Mode().Perm() != 0600 {
		_ = f.Close()
		return nil, errStore
	}
	deadline := time.NewTimer(10 * time.Second)
	defer deadline.Stop()
	for {
		err = syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB)
		if err == nil {
			return func() { _ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN); _ = f.Close() }, nil
		}
		if !errors.Is(err, syscall.EWOULDBLOCK) {
			_ = f.Close()
			return nil, errStore
		}
		select {
		case <-ctx.Done():
			_ = f.Close()
			return nil, errStore
		case <-deadline.C:
			_ = f.Close()
			return nil, errStore
		case <-time.After(20 * time.Millisecond):
		}
	}
}
func readJournal(dir string) (journal, error) {
	s := journal{Version: 1, Routes: map[string]routeState{}}
	path := filepath.Join(dir, "state.json")
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		if _, markerErr := os.Lstat(filepath.Join(dir, "initialized")); !errors.Is(markerErr, os.ErrNotExist) {
			return journal{}, errStore
		}
		return s, nil
	}
	if err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0077 != 0 || info.Size() > 128*1024 {
		return journal{}, errStore
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return journal{}, errStore
	}
	d := json.NewDecoder(strings.NewReader(string(b)))
	d.DisallowUnknownFields()
	if d.Decode(&s) != nil || !errors.Is(d.Decode(new(any)), io.EOF) || s.Version != 1 || s.Routes == nil || len(s.Routes) > len(routes) || len(s.Pending) > 64 || len(s.Receipts) > 128 || s.AttemptCount < 0 || s.AttemptCount > 12 {
		return journal{}, errStore
	}
	if s.AttemptDay != "" {
		if _, err := time.Parse("2006-01-02", s.AttemptDay); err != nil {
			return journal{}, errStore
		}
	} else if s.AttemptCount != 0 {
		return journal{}, errStore
	}
	for name, r := range s.Routes {
		if _, ok := routes[name]; !ok || r.Issue < 0 || !validState(r.State) || r.ObservedAt.IsZero() {
			return journal{}, errStore
		}
		if r.Episode != "" && !validID(r.Episode) || r.Issue > 0 && r.Episode == "" || r.State == "firing" && r.Episode == "" {
			return journal{}, errStore
		}
	}
	ids := map[string]bool{}
	for _, r := range s.Receipts {
		if !validID(r.Operation) || r.Issue <= 0 || r.Comment < 0 || r.VerifiedAt.IsZero() || ids[r.Operation] {
			return journal{}, errStore
		}
		ids[r.Operation] = true
	}
	for _, op := range s.Pending {
		if _, ok := routes[op.Route]; !ok || !validID(op.ID) || !validID(op.Episode) || op.CreatedAt.IsZero() || op.Issue < 0 || op.Attempts < 0 || op.Attempts > 6 || ids[op.ID] || op.Episode != s.Routes[op.Route].Episode {
			return journal{}, errStore
		}
		ids[op.ID] = true
		if !validState(op.State) {
			return journal{}, errStore
		}
	}
	return s, nil
}

func validID(id string) bool {
	if len(id) != 32 {
		return false
	}
	_, err := hex.DecodeString(id)
	return err == nil
}
func validState(state string) bool {
	return state == "firing" || state == "healthy" || state == "unknown"
}
func saveJournal(dir string, s journal) error {
	b, err := json.Marshal(s)
	if err != nil || len(b) > 128*1024 {
		return errStore
	}
	f, err := os.CreateTemp(dir, ".state-*")
	if err != nil {
		return errStore
	}
	name := f.Name()
	defer os.Remove(name)
	if _, err = f.Write(b); err != nil {
		_ = f.Close()
		return errStore
	}
	if err = f.Sync(); err != nil {
		_ = f.Close()
		return errStore
	}
	if f.Close() != nil || os.Rename(name, filepath.Join(dir, "state.json")) != nil {
		return errStore
	}
	if ensureInitialized(dir) != nil {
		return errStore
	}
	d, err := os.Open(dir)
	if err != nil {
		return errStore
	}
	defer d.Close()
	if d.Sync() != nil {
		return errStore
	}
	return nil
}

func ensureInitialized(dir string) error {
	path := filepath.Join(dir, "initialized")
	f, err := os.OpenFile(path, os.O_CREATE|os.O_EXCL|os.O_WRONLY|syscall.O_NOFOLLOW, 0600)
	if err == nil {
		if _, err = f.WriteString("v1\n"); err != nil {
			_ = f.Close()
			return errStore
		}
		if f.Sync() != nil {
			_ = f.Close()
			return errStore
		}
		if f.Close() != nil {
			return errStore
		}
		return nil
	}
	if !errors.Is(err, os.ErrExist) {
		return errStore
	}
	f, err = os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		return errStore
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil || !info.Mode().IsRegular() || info.Mode().Perm() != 0600 || info.Size() != 3 {
		return errStore
	}
	b, err := io.ReadAll(io.LimitReader(f, 4))
	if err != nil || string(b) != "v1\n" {
		return errStore
	}
	return nil
}
