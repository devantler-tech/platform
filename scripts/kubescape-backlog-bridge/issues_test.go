// truncationSuffix is what renderTitle appends when it cuts an over-long key:
// the disclosure ellipsis followed by the 8-hex distinctness digest.
var truncationSuffix = regexp.MustCompile(`…[0-9a-f]{8}$`)

// postureTheme and cveTheme are the two shapes the reconciler sees.
func postureTheme(key string, components ...string) theme {
	return theme{
		Kind:       string(surfacePosture),
		Key:        key,
		Severity:   "High",
		Components: components,
		Count:      len(components),
	}
}

func cveTheme(key string, total int, components ...string) theme {
	return theme{
		Kind:       string(surfaceCVE),
		Key:        key,
		Severity:   key,
		Components: components,
		Count:      len(components),
		Total:      total,
	}
}

// goldenPostureBody is the EXACT body a current run writes for
// postureTheme("C-0016", "apps/Deployment/web").
//
// It is a literal rather than a renderBody() call, and that is the whole point.
// The zero-write property below asserts that an unchanged theme renders
// identically to what is already filed; if the existing body were produced by
// calling renderBody in the test, the comparison would hold for ANY renderBody
// — including one that embedded a timestamp, which is precisely the instability
// that would turn every run into an update. Pinning the bytes here means a
// format drift fails this test instead of silently churning the backlog.
const goldenPostureBody = "> 🤖 Generated by the Agentic Engineer\n\n" +
	"<!-- kubescape-backlog-bridge:fingerprint=" + goldenPostureFingerprint + " -->\n" +
	"<!-- kubescape-backlog-bridge:identity=" + goldenPostureIdentity + " -->\n\n" +
	"Filed automatically from live Kubescape findings by " +
	"`scripts/kubescape-backlog-bridge`. Part of #2854.\n\n" +
	"**Surface:** posture\n" +
	"**Severity:** High\n" +
	"\n**Affected components (1):**\n\n" +
	"- `apps/Deployment/web`\n" +
	"\nThis issue is reconciled automatically: it is updated when the affected set " +
	"changes and closed when the finding is gone. Edit the title or body only if you are " +
	"willing to have it overwritten — the fingerprint comment above is what identifies it.\n"

// goldenPostureFingerprint pins sha256("posture|C-0016")[:16], computed
// independently of this package: `printf 'posture|C-0016' | shasum -a 256`.
const goldenPostureFingerprint = "43379dbb9d5d9566"

// goldenPostureIdentity pins the complete SHA-256 of "posture|C-0016".
// The fingerprint above is its historical 64-bit prefix.
const goldenPostureIdentity = "43379dbb9d5d956670135e3efe28ce2b076d40d197e788c71073fc3f76b8e193"

// legacyGoldenPostureBody is the exact pre-identity-marker format already
// filed in GitHub. The removed line is a hand-pinned literal, not production
// output, so this stays an independent migration fixture.
var legacyGoldenPostureBody = strings.Replace(goldenPostureBody,
	"<!-- kubescape-backlog-bridge:identity="+goldenPostureIdentity+" -->\n", "", 1)

const goldenPostureTitle = "security(posture): C-0016 fails"

func TestRenderMatchesGolden(t *testing.T) {
	th := postureTheme("C-0016", "apps/Deployment/web")

	if got := th.Fingerprint(); got != goldenPostureFingerprint {
		t.Fatalf("fingerprint drifted: got %q want %q", got, goldenPostureFingerprint)
	}

	if got := renderTitle(th); got != goldenPostureTitle {
		t.Errorf("title drifted:\n got %q\nwant %q", got, goldenPostureTitle)
	}

	if got := renderBody(th); got != goldenPostureBody {
		t.Errorf("body drifted:\n got %q\nwant %q", got, goldenPostureBody)
	}
}

// TestRenderIsDeterministic guards the anti-churn guarantee at its source: two
// renders of one theme must be byte-identical, so an unchanged cluster writes
// nothing.
//
// renderBody PRESERVES the component order it is given; it does not impose one.
// That is deliberate — the canonical order is established once, by assemble,
// and TestAssembleSortsEveryCollection is what pins it. Asserting
// order-independence here would demand a property renderBody is not required to
// have, and would move the guarantee away from the function that provides it.
func TestRenderIsDeterministic(t *testing.T) {
	a := renderBody(postureTheme("C-0016", "apps/Deployment/web", "db/StatefulSet/pg"))
	b := renderBody(postureTheme("C-0016", "apps/Deployment/web", "db/StatefulSet/pg"))

	if a != b {
		t.Fatalf("renderBody is not deterministic:\n%q\n%q", a, b)
	}
}

func trackedPosture(number int, open bool) backlogEntry {
	return backlogEntry{Number: number, Title: goldenPostureTitle, Body: goldenPostureBody, Open: open}
}

// TestUnchangedStateProducesNoWrites is the acceptance criterion "no issue
// spam: unchanged cluster state produces zero writes", asserted as a property.
func TestUnchangedStateProducesNoWrites(t *testing.T) {
	themes := []theme{postureTheme("C-0016", "apps/Deployment/web")}
	existing := []backlogEntry{trackedPosture(41, true)}

	p, err := planWrites(themes, existing, []surface{surfacePosture}, true, nil)
	if err != nil {
		t.Fatalf("planWrites: %v", err)
	}

	if !p.empty() {
		t.Fatalf("unchanged state planned %d write(s): %+v", len(p.Actions), p.Actions)
	}

	// CONTROL — the assertion above must be capable of failing. One byte of
	// drift in the tracked body has to produce an update; if it does not, the
	// comparison is vacuous and the empty plan above proved nothing.
	drifted := []backlogEntry{{
		Number: 41,
		Title:  goldenPostureTitle,
		Body:   strings.Replace(goldenPostureBody, "apps/Deployment/web", "apps/Deployment/api", 1),
		Open:   true,
	}}

	if drifted[0].Body == goldenPostureBody {
		t.Fatal("control is inert: the substitution did not change the body")
	}

	ctrl, err := planWrites(themes, drifted, []surface{surfacePosture}, true, nil)
	if err != nil {
		t.Fatalf("control planWrites: %v", err)
	}

	if len(ctrl.Actions) != 1 || ctrl.Actions[0].Kind != "update" {
		t.Fatalf("control did not flip: want one update, got %+v", ctrl.Actions)
	}
}

