// TestPreviouslyFiledFingerprintCollisionIsRefused is the ablation proof for
// the stored-identity comparison. Removing that comparison makes planWrites
// silently adopt issue #41 for C-0017 and this test fail.
func TestPreviouslyFiledFingerprintCollisionIsRefused(t *testing.T) {
	const (
		incomingFingerprint = "cffda777fdcd1a44"
		incomingIdentity    = "cffda777fdcd1a44cfac478b956ceeac9e28926ded3951fce3cc25769c677e45"
		storedIdentity      = "cffda777fdcd1a4470135e3efe28ce2b076d40d197e788c71073fc3f76b8e193"
	)

	entry := backlogEntry{
		Number: 41,
		Title:  goldenPostureTitle,
		Body: strings.Replace(strings.Replace(goldenPostureBody,
			goldenPostureFingerprint, incomingFingerprint, 1),
			goldenPostureIdentity, storedIdentity, 1),
		Open: true,
	}

	p, err := planWrites([]theme{postureTheme("C-0017", "apps/Deployment/api")},
		[]backlogEntry{entry}, []surface{surfacePosture}, true, nil)
	if err == nil {
		t.Fatalf("colliding theme silently adopted issue #41: %+v", p.Actions)
	}

	for _, want := range []string{
		storedIdentity,
		incomingIdentity,
		goldenPostureTitle,
		"posture/C-0017",
	} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("collision error %q does not name %q", err, want)
		}
	}

	if len(p.Actions) != 0 {
		t.Errorf("a refused plan must queue nothing, got %+v", p.Actions)
	}
}

