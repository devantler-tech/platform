// TestPartialInputReopenKeepsFiledScope covers the one write a partial run must
// still perform. Leaving a live finding closed is worse than a stale body, so
// the state change happens — but carrying the subset render into it would strip
// the entry back to what this run happened to look at, which is the very loss
// the update gate above exists to prevent.
