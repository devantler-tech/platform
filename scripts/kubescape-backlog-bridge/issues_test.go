// TestPartialInputWithholdsUpdate is the non-destructive half of the same gate
// TestCloseRequiresInputsComplete covers, and it exists because "non-destructive"
// was the wrong word for it. A theme derived from a subset lists only that
// subset's components, so writing it over a tracked entry DELETES the components
// this run never examined — recorded scope lost while the findings are still
// live, which reads to a human exactly like remediation.
func TestPartialInputWithholdsUpdate(t *testing.T) {
	// Deliberately SHRINKING: the tracked entry names one component and this
	// derivation names a different one, so the rendered bodies differ and the
	// byte-comparison short circuit cannot be what withholds the write.
	subset := postureTheme("C-0016", "db/StatefulSet/pg")
	existing := []backlogEntry{trackedPosture(41, true)}

	p, err := planWrites([]theme{subset}, existing, []surface{surfacePosture}, false, nil)
	if err != nil {
		t.Fatalf("planWrites: %v", err)
	}

	if !p.empty() {
		t.Fatalf("a partial run planned writes: %+v", p.Actions)
	}

	if p.WithheldUpdates != 1 {
		t.Errorf("want 1 withheld update disclosed, got %d", p.WithheldUpdates)
	}

	// CONTROL — the same input with the completeness assertion must update.
	// Without it this test would pass for a planner that never updates at all.
	ctrl, err := planWrites([]theme{subset}, existing, []surface{surfacePosture}, true, nil)
	if err != nil {
		t.Fatalf("control planWrites: %v", err)
	}

	if len(ctrl.Actions) != 1 || ctrl.Actions[0].Kind != "update" || ctrl.Actions[0].Number != 41 {
		t.Fatalf("control did not flip: want one update of #41, got %+v", ctrl.Actions)
	}

	if ctrl.WithheldUpdates != 0 {
		t.Errorf("control must withhold nothing, got %d", ctrl.WithheldUpdates)
	}
}

