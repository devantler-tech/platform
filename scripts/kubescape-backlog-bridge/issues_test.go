// TestBoundFieldKeepsOverlongComponentsDistinct pins the identity half of the
// field bound. Truncation exists so one malformed value cannot push a body past
// GitHub's limit; it must not achieve that by making two real resources
// indistinguishable, because naming the affected resources is what the list is
// for. A prefix-only cut renders `…-a` and `…-b` as the same bullet while the
// component COUNT still reads correct — right number, unusable identities.
func TestBoundFieldKeepsOverlongComponentsDistinct(t *testing.T) {
	shared := "prod/Deployment/" + strings.Repeat("x", maxRenderedFieldRunes+40)
	a, b := boundField(shared+"-alpha"), boundField(shared+"-beta")

	// The fixture must actually exercise truncation, or this proves nothing.
	if utf8.RuneCountInString(shared+"-alpha") <= maxRenderedFieldRunes {
		t.Fatal("fixture is inert: the input is inside the bound, so nothing is truncated")
	}

	if a == b {
		t.Errorf("two distinct components collapsed to one bullet:\n%q", a)
	}

	// Distinctness must not come at the cost of the bound it exists to enforce.
	for _, got := range []string{a, b} {
		if n := utf8.RuneCountInString(got); n > maxRenderedFieldRunes {
			t.Errorf("bounded field is %d runes, over the %d limit: %q", n, maxRenderedFieldRunes, got)
		}
	}

	// Determinism, or the anti-churn guarantee breaks: an unchanged component
	// must render identically on every run.
	if boundField(shared+"-alpha") != a {
		t.Error("boundField is not deterministic; every run would rewrite the issue")
	}

	// A value inside the bound must be returned untouched — no digest, no
	// ellipsis. Otherwise the ordinary case would churn every tracked issue.
	if got := boundField("prod/Deployment/web"); got != "prod/Deployment/web" {
		t.Errorf("a short component was altered: %q", got)
	}
}

// TestReclassifyPostsNothingWhenTheStateChangeFails pins the ORDER inside
// reclassify, by asserting the consequence of that order rather than the order
// itself.
//
// reclassify makes two calls, and planWrites re-derives the same action from the
// same inputs on every run — so whichever call fails is retried next run. If the
// comment went first, a PATCH that keeps failing would post the same comment
// again on every run, accumulating duplicates on a settled issue with no bound.
// Doing the state change first makes a failure post nothing at all, so the retry
// is idempotent.
//
// Asserting "PATCH is argv[0]" would pass just as well with the comment posted
// first and the PATCH second, which is the bug. The guarantee is that a failed
// state change leaves NO comment behind.
func TestReclassifyPostsNothingWhenTheStateChangeFails(t *testing.T) {
	var calls []string

	store := &ghStore{repo: "o/r", run: func(a ...string) ([]byte, error) {
		calls = append(calls, strings.Join(a, " "))

		if a[0] == "api" {
			return nil, errors.New("422 unprocessable")
		}

		return nil, nil
	}}

	if err := store.reclassify(7, "why this changed", dispositionNotPlanned); err == nil {
		t.Fatal("reclassify returned nil, want the PATCH failure surfaced so applyPlan stops")
	}

	for _, c := range calls {
		if strings.HasPrefix(c, "issue comment") {
			t.Errorf("a comment was posted despite the state change failing: %q\n"+
				"the next run re-derives the same disagreement, so this comment repeats forever", c)
		}
	}

	// Without this the test would also pass if reclassify made no calls at all.
	if len(calls) != 1 {
		t.Fatalf("made %d call(s) %q, want exactly the failing PATCH", len(calls), calls)
	}
}

// TestReclassifyExplainsItselfWhenTheStateChangeSucceeds is the other half:
// ordering the PATCH first must not silently drop the explanation on the happy
// path, which is the whole reason the comment exists.
func TestReclassifyExplainsItselfWhenTheStateChangeSucceeds(t *testing.T) {
	var calls []string

	store := &ghStore{repo: "o/r", run: func(a ...string) ([]byte, error) {
		calls = append(calls, strings.Join(a, " "))

		return nil, nil
	}}

	if err := store.reclassify(7, "why this changed", dispositionNotPlanned); err != nil {
		t.Fatalf("reclassify: %v", err)
	}

	if len(calls) != 2 {
		t.Fatalf("made %d call(s) %q, want the PATCH and the comment", len(calls), calls)
	}

	if !strings.HasPrefix(calls[0], "api --method PATCH") {
		t.Errorf("first call = %q, want the state change", calls[0])
	}

	if !strings.HasPrefix(calls[1], "issue comment") {
		t.Errorf("second call = %q, want the explaining comment", calls[1])
	}

	if !strings.Contains(calls[0], "state_reason=not_planned") {
		t.Errorf("PATCH = %q, want the REST underscore spelling", calls[0])
	}

	// The REST API ignores state_reason unless state travels with it, so a PATCH
	// carrying the reason alone succeeds while changing nothing. That failure is
	// invisible to the caller — it returns no error — and the next run re-derives
	// the same disagreement forever. Asserting the reason alone would pass
	// against exactly that broken request.
	if !strings.Contains(calls[0], "state=closed") {
		t.Errorf("PATCH = %q, want state=closed so the API honours state_reason", calls[0])
	}

	if !strings.Contains(calls[1], "why this changed") {
		t.Errorf("comment = %q, want the caller's explanation", calls[1])
	}
}

// TestIssueReferencesAreNeutralised stops scan output from cross-referencing an
// unrelated issue.
//
// GitHub turns "#123" into a link AND posts a cross-reference event on issue
// 123, so a crafted or malformed scanner value would generate notifications and
// timeline noise on an issue nobody chose to involve — from this command's own
// authenticated account.
//
// Severity is the field that proves it matters: components render INSIDE a code
// span, which does suppress the autolink, but Severity renders outside one. A
// value's safety must not depend on where it happens to be interpolated.
func TestIssueReferencesAreNeutralised(t *testing.T) {
	th := postureTheme("C-0016", "apps/Deployment/web")
	th.Severity = "unknown bucket #2854 see also"

	body := renderBody(th)

	if strings.Contains(body, "#2854 see") {
		t.Fatalf("a live issue reference survived into the body: %q", body)
	}

	if !strings.Contains(body, "#"+zeroWidthSpace+"2854") {
		t.Errorf("the reference was not broken as expected: %q", body)
	}

	// CONTROL — the value must survive apart from the broken token, so this does
	// not pass merely because rendering dropped the field.
	if !strings.Contains(body, "unknown bucket") || !strings.Contains(body, "2854 see also") {
		t.Errorf("sanitising destroyed the value instead of breaking the token: %q", body)
	}

	// CONTROL — the body's OWN legitimate "Part of #2854" reference is written by
	// renderBody itself, not through the sanitiser, and must stay live. Without
	// this, neutralising every "#" everywhere would look like a pass.
	if !strings.Contains(body, "Part of #2854.") {
		t.Errorf("the body's own issue reference was broken; only scanner-derived fields are sanitised: %q", body)
	}
}

// TestDuplicateSurfaceMarkerIsRefused keeps an edited body from retargeting
// which surface a tracked entry claims to belong to.
//
// entrySurface decides whether a run "examined" an entry's surface, which is
// what authorizes closing and reclassifying it. Taking the FIRST match would let
// a line inserted above the genuine one flip a posture entry to cve, so a
// CVE-only run would close a posture finding it never scanned — the fail-open
// direction for a security backlog.
//
// Refusing on duplication rather than preferring one of them is deliberate: with
// two markers present there is no principled way to tell the genuine one from
// the forged one, and "" makes the gates withhold.
func TestDuplicateSurfaceMarkerIsRefused(t *testing.T) {
	genuine := renderBody(postureTheme("C-0016", "apps/Deployment/web"))

	// CONTROL — the untouched body must resolve, or the test below would pass
	// against a function that refuses everything.
	if got := entrySurface(backlogEntry{Body: genuine}); got != surfacePosture {
		t.Fatalf("untouched body resolved to %q, want %q", got, surfacePosture)
	}

	for _, c := range []struct {
		name string
		body string
	}{
		{"forged line inserted ABOVE the genuine one",
			"**Surface:** " + string(surfaceCVE) + "\n" + genuine},
		{"forged line appended BELOW the genuine one",
			genuine + "\n**Surface:** " + string(surfaceCVE) + "\n"},
		{"the genuine line edited to another valid surface, duplicated",
			genuine + "\n**Surface:** " + string(surfacePosture) + "\n"},
	} {
		if got := entrySurface(backlogEntry{Body: c.body}); got != "" {
			t.Errorf("%s: resolved to %q, want \"\" so the lifecycle gates withhold", c.name, got)
		}
	}
}

// TestSanitizeForIssueBreaksHTMLTags pins the "<" case of sanitizeForIssue.
//
// GitHub renders inline HTML inside Markdown, and Severity reaches the body
// OUTSIDE a code span, so an unknown posture severity or CVE bucket carrying
// "<details><summary>" emits real structure — collapsing the affected-component
// list this issue exists to show. Scan output is untrusted, so the value must be
// inert wherever it lands.
func TestSanitizeForIssueBreaksHTMLTags(t *testing.T) {
	hostile := "<details><summary>hidden</summary>"

	got := sanitizeForIssue(hostile)

	// An intact "<" immediately followed by a tag character is what GitHub
	// parses. The zero-width space between them is what makes it inert.
	if strings.Contains(got, "<d") || strings.Contains(got, "</") {
		t.Errorf("HTML tag survived sanitization and would render live:\n%q", got)
	}

	// The information is broken, not destroyed — a reader still sees the value.
	if !strings.Contains(got, "details") || !strings.Contains(got, "summary") {
		t.Errorf("sanitization removed the value instead of neutralising it:\n%q", got)
	}

	// Determinism, or the anti-churn guarantee breaks.
	if sanitizeForIssue(hostile) != got {
		t.Error("sanitizeForIssue is not deterministic; every run would rewrite the issue")
	}
}

// TestRenderTitleKeepsOverlongKeysDistinct is the title-side twin of
// TestBoundFieldKeepsOverlongComponentsDistinct.
