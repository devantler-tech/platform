#!/bin/sh
# Coroot v1.28.1's API owns persistence; this job owns only the three named
# dashboards carrying the marker below. Source: coroot/coroot api/api.go,
# api/forms/forms.go, db/dashboards.go at tag v1.28.1.
set -eu

COROOT_URL=${COROOT_URL:-http://coroot-coroot.observability.svc.cluster.local.:8080}
COROOT_PROJECT=${COROOT_PROJECT:-platform}
DASHBOARDS_FILE=${DASHBOARDS_FILE:-/config/dashboards.json}
COROOT_CONNECT_TIMEOUT=${COROOT_CONNECT_TIMEOUT:-5}
COROOT_REQUEST_TIMEOUT=${COROOT_REQUEST_TIMEOUT:-30}
# db/dashboards.go serialises every metrics query with "scope", "" when unset.
# An empty scope is the default (the project client still adds its selector),
# so compare the persisted configuration without it.
persisted_config='(.data.config | del(.. | .scope? | select(. == "")))'

owner='> 🤖 Generated by the Agentic Engineer

Managed by platform GitOps: coroot-security-progress/v1.
'

fail() {
  echo "ERROR: $*" >&2
  exit 1
}

# Private response bodies never reach logs. No POST is automatically retried:
# create is not idempotent when the server commits but its response is lost.
# The next scheduled run re-discovers the named dashboard instead.
request() {
  method=$1
  path=$2
  expected=$3
  body=${4:-}
  if [ "$method" = POST ]; then
    code=$(curl --silent --show-error --max-time "$COROOT_REQUEST_TIMEOUT" \
      --connect-timeout "$COROOT_CONNECT_TIMEOUT" --output "$tmp/response" \
      --write-out '%{http_code}' --request POST --header 'content-type: application/json' \
      --data-binary "$body" "${COROOT_URL%/}$path") || fail "$method request failed"
  else
    code=$(curl --silent --show-error --max-time "$COROOT_REQUEST_TIMEOUT" \
      --connect-timeout "$COROOT_CONNECT_TIMEOUT" --output "$tmp/response" \
      --write-out '%{http_code}' "${COROOT_URL%/}$path") || fail "$method request failed"
  fi
  [ "$code" = "$expected" ] || fail "$method returned HTTP $code; expected $expected"
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM

# Validate the complete desired set before any API writes. The input cannot
# expand ownership to an arbitrary operator dashboard by changing a name.
jq -e --arg owner "$owner" '
  type == "array" and length > 0
  and ([.[].name] | length == (unique | length))
  and all(.[];
    (.name == "Platform security progress" or
     .name == "Kyverno remaining policy findings" or
     .name == "Kubescape remediation progress")
    and (.description | type == "string" and startswith($owner))
    and (.config | type == "object")
    and (.config.groups | type == "array")
  )' "$DASHBOARDS_FILE" >/dev/null || fail 'invalid or unowned dashboard definitions'

request GET /api/user 200
pid=$(jq -er --arg name "$COROOT_PROJECT" '
  [.projects[]? | select(.name == $name)]
  | if length == 1 and (.[0].id | type == "string" and length > 0)
    then .[0].id else error("project missing or ambiguous") end
' "$tmp/response") || fail 'project discovery failed or was ambiguous'
project_path=$(printf '%s' "$pid" | jq -sRr @uri)
collection="/api/project/$project_path/dashboards"

read_list() {
  request GET "$collection" 200
  jq -e '.data | type == "array" and all(.[];
    (.id | type == "string" and length > 0) and
    (.name | type == "string") and (.description | type == "string"))' \
    "$tmp/response" >/dev/null || fail 'dashboard list unavailable or invalid'
  cp "$tmp/response" "$tmp/list"
}

# Refuse all collisions before provisioning any of the requested dashboards.
# A same-name operator dashboard is never adopted, even when its config matches.
check_ownership() {
  jq -e --arg owner "$owner" --slurpfile desired "$DASHBOARDS_FILE" '
    .data as $live | all($desired[0][];
      .name as $name | [$live[] | select(.name == $name)] as $matches
      | ($matches | length) <= 1
        and all($matches[]; .description | startswith($owner)))
  ' "$tmp/list" >/dev/null || fail 'dashboard name is duplicated or owned by someone else'
}

read_list
check_ownership
count=$(jq length "$DASHBOARDS_FILE")
index=0
while [ "$index" -lt "$count" ]; do
  jq --argjson index "$index" '.[$index]' "$DASHBOARDS_FILE" >"$tmp/desired"
  name=$(jq -r .name "$tmp/desired")
  # Rebind ownership before each write sequence in case another actor changed
  # the catalogue after preflight. CronJob concurrencyPolicy forbids self races.
  read_list
  check_ownership
  id=$(jq -r --arg name "$name" '.data[] | select(.name == $name) | .id' "$tmp/list")
  if [ -z "$id" ]; then
    body=$(jq -c '{action:"create",name,description}' "$tmp/desired")
    request POST "$collection" 201 "$body"
    id=$(cat "$tmp/response")
    [ -n "$id" ] || fail 'create returned an empty dashboard id'
    read_list
    check_ownership
    jq -e --arg id "$id" --arg name "$name" \
      '[.data[] | select(.name == $name)] | length == 1 and .[0].id == $id' \
      "$tmp/list" >/dev/null || fail 'created dashboard was not found by its owned name and id'
  fi
  dashboard_path=$(printf '%s' "$id" | jq -sRr @uri)
  endpoint="$collection/$dashboard_path"
  request GET "$endpoint" 200
  jq -e --arg id "$id" --arg name "$name" '
    .data | type == "object" and .id == $id and .name == $name
      and (.config | type == "object")
  ' "$tmp/response" >/dev/null || fail 'dashboard detail unavailable or does not match its owned identity'
  cp "$tmp/response" "$tmp/current"

  # In v1.28.1 detail GET does not load description; compare against the list.
  if ! jq -e --arg id "$id" --slurpfile desired "$tmp/desired" \
    'any(.data[]; .id == $id and .description == $desired[0].description)' \
    "$tmp/list" >/dev/null; then
    body=$(jq -c '{action:"update",name,description}' "$tmp/desired")
    request POST "$endpoint" 200 "$body"
  fi
  if ! jq -e --slurpfile desired "$tmp/desired" \
    "$persisted_config"' == $desired[0].config' "$tmp/current" >/dev/null; then
    # DashboardForm embeds db.Dashboard flat. A nested dashboard object or a
    # metadata-only update silently leaves the persisted configuration unchanged.
    body=$(jq -c '{name,config}' "$tmp/desired")
    request POST "$endpoint" 200 "$body"
  fi

  # A 200 alone is not convergence: a warming project may return context/null.
  request GET "$endpoint" 200
  jq -e --arg id "$id" --slurpfile desired "$tmp/desired" \
    '.data.id == $id and .data.name == $desired[0].name and '"$persisted_config"' == $desired[0].config' \
    "$tmp/response" >/dev/null || fail 'dashboard configuration did not persist'
  read_list
  check_ownership
  jq -e --arg id "$id" --slurpfile desired "$tmp/desired" \
    'any(.data[]; .id == $id and .name == $desired[0].name and .description == $desired[0].description)' \
    "$tmp/list" >/dev/null || fail 'dashboard metadata did not persist'
  echo "Dashboard reconciled: $name"
  index=$((index + 1))
done
